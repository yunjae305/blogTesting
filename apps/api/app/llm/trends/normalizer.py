"""표기만 다른 같은 키워드를 하나로 본다 — 비교용 normalizedKeyword.

같은 키워드가 소스마다 다른 표기로 오거나("리그 오브 레전드" vs "LOL"), 새로고침
사이에 조사/연도만 바뀌어 다시 올라오는 것을 막으려면, 두 문자열이 "사실상 같은
키워드"인지 한 곳에서 판단해야 한다. 이 함수가 만든 값이 같으면 같은 키워드다.

먼저 문자열 규칙(공백·대소문자·기호·연도·조사)으로 처리하고, 문자열로는 묶이지
않는 잘 알려진 동의어만 작은 별칭표로 잇는다. 트렌드 결과를 여기에 고정하는 것이
아니라(§10), 오직 "같은 것끼리 묶기" 위한 목록이다.
"""

import re

# 문자열 규칙으로는 묶이지 않는, 널리 통용되는 동의어. 정규화(공백 제거·소문자)를
# 거친 뒤의 형태를 key로 둔다.
_ALIASES = {
    "lol": "리그오브레전드",
    "롤": "리그오브레전드",
    "leagueoflegends": "리그오브레전드",
}

# 구글 트렌드가 한 낱말인 고유명사를 형태소 단위로 끊어 보내는 것을 되돌리는 표
# ("다이 소" → "다이소", "황강 댐" → "황강댐"). 구글이 실제로 그 형태로 응답하므로
# (SerpApi `trending_searches[].query`) 수집기가 손댈 여지 없이 그대로 들어온다.
#
# 규칙으로 풀지 않고 표로 두는 이유: 한국어 붙여쓰기 판정은 사전 없이는 불가능하다.
# 같은 응답에 "한화 대 kia"·"어린이 배우"처럼 띄어쓰기가 **맞는** 값이 함께 오므로,
# "한 음절 조각이면 붙인다" 같은 휴리스틱은 멀쩡한 키워드를 망가뜨린다. 새 사례가
# 보이면 여기에 한 줄 추가하는 것이 유일하게 안전한 확장 방법이다.
#
# key는 공백을 지우고 소문자로 만든 형태 — "다이 소"·"다 이소"·"다이소"가 모두 같은
# 항목에 걸린다. 연도 접두("2026 워터밤")는 지우지 않으므로 표에 걸리지 않는다.
_COMPOUND_NOUNS = {
    "다이소": "다이소",
    "황강댐": "황강댐",
    "초과근무": "초과근무",
}

_WHITESPACE = re.compile(r"\s+")


def repair_spacing(value: str) -> str:
    """표기용 형태를 고친다 — 잘못 끊긴 고유명사를 원래 한 낱말로 되돌린다.

    normalize_keyword와 목적이 다르다: 저쪽은 **비교용** 값을 만들고 화면 표기는 건드리지
    않는다. 이 함수가 만든 값은 화면에도 나가고 제목·원고 프롬프트에도 실리므로, 표에
    없는 키워드는 절대 바꾸지 않고 그대로 돌려준다.
    """
    text = (value or "").strip()
    if " " not in text:
        return text
    return _COMPOUND_NOUNS.get(_WHITESPACE.sub("", text).lower(), text)

# 앞에 붙은 연도: "2026 워터밤" → "워터밤". 같은 행사가 해마다 다른 연도로 오는 것을
# 한 키워드로 본다.
_LEADING_YEAR = re.compile(r"^(?:19|20)\d{2}")

# 비교에는 글자와 숫자만 쓴다. 공백·기호를 지우면 "리그 오브 레전드"와
# "리그오브레전드"가 같아진다. (한글·영문·숫자만 남긴다.)
_NON_WORD = re.compile(r"[^0-9a-z가-힣]")


def normalize_keyword(value: str) -> str:
    """두 키워드가 같은지 비교할 때 쓰는 정규 형태를 만든다.

    같은 것을 반환하면 같은 키워드로 취급한다. 원본 표기는 바꾸지 않는다 — 화면에는
    수집된 그대로 보여주고, 중복 판단에만 이 값을 쓴다.

    조사(§6의 "조사만 다른 경우")는 여기서 떼지 않는다. "가"·"는" 같은 한 글자
    조사를 떼면 "여름휴가"가 "여름휴"로 잘리는 등 멀쩡한 명사를 망가뜨리는데, 조사가
    붙은 후보는 수집 단계(is_noun_phrase)에서 이미 걸러지므로 얻을 것도 거의 없다.
    """
    text = (value or "").strip().lower()
    text = _LEADING_YEAR.sub("", text)
    text = _NON_WORD.sub("", text)
    if not text:
        return ""

    return _ALIASES.get(text, text)
